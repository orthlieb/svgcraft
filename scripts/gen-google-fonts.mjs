// Builds google-fonts.js — the full Google Fonts catalogue the font picker
// searches — from the google-font-metadata package (Fontsource's copy of
// the Google Fonts API listing).
//
//   npm pack google-font-metadata && tar xzf google-font-metadata-*.tgz
//   node scripts/gen-google-fonts.mjs path/to/package
//
// One line per family: name|category|weights|italic weights, a weight
// written as its first digit (4 = 400). Only the styles a family really
// ships are listed, since asking Google for a missing one fails the whole
// request.
import fs from 'node:fs';
import path from 'node:path';
import * as prettier from 'prettier';

const pkg = process.argv[2];
if (!pkg) throw new Error('Usage: node scripts/gen-google-fonts.mjs path/to/google-font-metadata');
const meta = JSON.parse(fs.readFileSync(path.join(pkg, 'package.json'), 'utf8'));
const list = JSON.parse(fs.readFileSync(path.join(pkg, 'data', 'api-response.json'), 'utf8'));
const CATS = { 'sans-serif': 's', serif: 'r', display: 'd', handwriting: 'h', monospace: 'm' };

const lines = [];
for (const f of list.sort((a, b) => a.family.localeCompare(b.family, 'en'))) {
  const cat = CATS[f.category];
  if (!cat || /[|'\\]/.test(f.family)) continue;
  const w = new Set();
  const iw = new Set();
  for (const v of f.variants) {
    const m = /^(\d00)?(regular|italic)?$/.exec(v);
    if (!m) continue;
    const weight = m[1] ? +m[1] : 400;
    (m[2] === 'italic' ? iw : w).add(weight / 100);
  }
  // A family that only ships italics still needs an upright entry to pick.
  if (!w.size) continue;
  const digits = (s) => [...s].sort().join('');
  lines.push(`${f.family}|${cat}|${digits(w)}|${digits(iw)}`);
}

const src = `// SVGCraft's Google Fonts catalogue — generated by
// scripts/gen-google-fonts.mjs from google-font-metadata ${meta.version};
// don't edit by hand. Loaded only when the font picker or a drawing needs
// it. Each entry: name|category (s sans-serif, r serif, d display,
// h handwriting, m monospace)|weights|italic weights, as hundreds (4 = 400).
'use strict';

window.SC_GOOGLE_FONTS = ${JSON.stringify(lines)};
`;
const out = path.resolve(import.meta.dirname, '..', 'google-fonts.js');
fs.writeFileSync(
  out,
  await prettier.format(src, { ...(await prettier.resolveConfig(out)), filepath: out }),
);
console.log(`wrote google-fonts.js: ${lines.length} families`);
