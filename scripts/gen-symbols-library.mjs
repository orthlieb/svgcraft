// Builds symbols-library.js — the Symbols library's built-in icon set — from
// the Font Awesome Free 6.7.2 package's SVGs (icons CC BY 4.0).
//
//   npm pack @fortawesome/fontawesome-free@6.7.2 && tar xzf fortawesome-*.tgz
//   node scripts/gen-symbols-library.mjs path/to/package
//
// Each icon keeps its viewBox size and its path data, and sets no fill of
// its own, so a placed instance draws it in the instance's fill colour.
import fs from 'node:fs';
import path from 'node:path';
import * as prettier from 'prettier';

const VERSION = '6.7.2';
const CREDIT = `Font Awesome Free ${VERSION} — CC BY 4.0`;

// [category, [[style/file, name?], …]]. Names default to the file's, in words.
const SET = [
  [
    'Arrows',
    [
      'arrow-right',
      'arrow-left',
      'arrow-up',
      'arrow-down',
      ['arrows-rotate', 'Refresh'],
      'share',
      'chevron-right',
      'chevron-left',
      'chevron-up',
      'chevron-down',
      ['arrow-rotate-left', 'Undo'],
      'expand',
      'compress',
    ],
  ],
  ['Shapes', ['star', 'heart', 'circle', 'square', 'play', ['location-pin', 'Map pin'], 'bolt']],
  [
    'Interface',
    [
      'check',
      ['xmark', 'Cross'],
      'plus',
      'minus',
      ['magnifying-glass', 'Search'],
      'gear',
      ['bars', 'Menu'],
      'house',
      'bell',
      'trash-can',
      'pen',
      'lock',
      'eye',
      'download',
      'upload',
      'link',
      'filter',
      'sliders',
      'bookmark',
    ],
  ],
  ['Communication', ['envelope', 'phone', 'comment', 'paper-plane']],
  ['Weather', ['sun', 'moon', 'cloud', 'cloud-rain', 'snowflake', 'umbrella']],
  ['People', ['user', 'users', 'child']],
  [
    'Objects',
    [
      'camera',
      'music',
      'gift',
      ['cart-shopping', 'Shopping cart'],
      'calendar',
      'clock',
      'book',
      'lightbulb',
      'flag',
      'tag',
      'briefcase',
      'key',
    ],
  ],
  ['Nature', ['leaf', 'tree', 'paw', 'fire']],
  ['Charts', ['chart-bar', 'chart-pie', 'chart-line']],
  ['Faces', ['face-smile', 'face-grin', 'face-laugh', 'face-meh', 'face-frown']],
  ['Places', ['globe', 'location-crosshairs', 'map', 'compass']],
];

const pkg = process.argv[2];
if (!pkg) {
  console.error('usage: node scripts/gen-symbols-library.mjs <fontawesome-free package dir>');
  process.exit(1);
}
const version = JSON.parse(fs.readFileSync(path.join(pkg, 'package.json'), 'utf8')).version;
if (version !== VERSION) throw new Error(`expected Font Awesome ${VERSION}, got ${version}`);

const words = (s) => s.replace(/-/g, ' ').replace(/^./, (c) => c.toUpperCase());
const out = [];
for (const [category, icons] of SET)
  for (const item of icons) {
    const [file, name] = Array.isArray(item) ? item : [item, words(item)];
    const style = file.includes('/') ? '' : 'solid/';
    const src = fs.readFileSync(path.join(pkg, 'svgs', `${style}${file}.svg`), 'utf8');
    const vb = /viewBox="0 0 (\d+(?:\.\d+)?) (\d+(?:\.\d+)?)"/.exec(src);
    const paths = [...src.matchAll(/<path d="([^"]+)"\s*\/>/g)].map((m) => m[1]);
    if (!vb || !paths.length) throw new Error(`can't read ${file}.svg`);
    out.push({
      id: file.replace(/^.*\//, ''),
      name,
      category,
      w: +vb[1],
      h: +vb[2],
      svg: paths.map((d) => `<path d="${d}"/>`).join(''),
      credit: CREDIT,
    });
  }

const header = `// SVGCraft's built-in Symbols library — generated by
// scripts/gen-symbols-library.mjs; don't edit by hand.
//
// Icons from Font Awesome Free ${VERSION} by Fonticons, Inc.
// (https://fontawesome.com), licensed CC BY 4.0
// (https://creativecommons.org/licenses/by/4.0/). Each entry: id, name,
// category, w × h (its viewBox), svg (content in that viewBox, no fill of
// its own) and credit, which travels into the drawing with a placed icon.
'use strict';

window.SC_SYMBOLS = ${JSON.stringify(out)};
`;
const file = path.resolve(import.meta.dirname, '..', 'symbols-library.js');
const opts = (await prettier.resolveConfig(file)) || {};
fs.writeFileSync(file, await prettier.format(header, { ...opts, filepath: file }));
console.log(`wrote ${out.length} icons to ${path.relative(process.cwd(), file)}`);
